import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const paths = ['data/source-candidates-core.json','data/source-candidates-tech.json','data/source-candidates-clinical-policy.json'];
const quality = JSON.parse(await fs.readFile(new URL('data/source-quality-overrides.json',root),'utf8').catch(()=>'{"sources":{},"publisherAliases":{}}'));
const candidates = [];
for (const path of paths) {
  const document=JSON.parse(await fs.readFile(new URL(path,root),'utf8'));
  candidates.push(...(Array.isArray(document)?document:document.candidates).map(source=>({...source,...quality.sources?.[source.id],auditFile:path})));
}
const key = value => { const url=new URL(value);url.hash='';return url.href.replace(/\/$/,''); };
const publishers = new Map([
  ['MIT','Massachusetts Institute of Technology'],['Google AI','Google'],['Google Research','Google'],['Together','Together AI'],
  ['Berkeley','University of California Berkeley'],['BAIR','University of California Berkeley'],
  ['CMU','Carnegie Mellon University'],['Stanford','Stanford University'],
]);
for (const [from,to] of Object.entries(quality.publisherAliases || {})) publishers.set(from,to);
function metadata(source) {
  const v=source.validation || {};
  const journal = source.contentType==='journal' || /(?:nature\.com\/.+\.rss|jamanetwork\.com\/rss\/|journals\.plos\.org\/|\.jmir\.org\/feed|\.bmj\.com\/.*rss)/i.test(source.url) && !/^https:\/\/www\.nature\.com\/nature\.rss$/i.test(source.url);
  let name=source.name.replace(/&raquo;/gi,'»').replace(/&amp;/gi,'&');
  if (/ — .*Feed$/i.test(name)) name=name.split(' — ')[0];
  if (source.url==='https://blog.google/rss/') name='Google — The Keyword';
  return {
    id:source.id,name,url:source.url,siteUrl:source.siteUrl,
    publisher:publishers.get(source.publisher)||source.publisher||source.name,
    kind:journal?'research':source.kind,
    ...(source.category?{category:source.category}:{}),
    aiOnly:source.aiOnly===true,
    ...(journal?{contentType:'journal'}:{}),
    trustReason:journal?'Original scholarly journal feed; mixed content must pass explicit AI relevance filtering.':source.trustReason,
    discoveryUrl:source.discoveryUrl,
    verifiedAt:v.checkedAt,
  };
}
const active=[],audit=[],seen=new Map(),fingerprints=new Map();
for (const source of candidates) {
  const v=source.validation||{};
  let reason;
  if (source.enabled===false || source.excludeFromLive) reason=source.disabledReason||source.excludeFromLive||'Endpoint did not pass source screening';
  else if (!(v.validFeed===true || source.enabled===true)) reason=v.error||v.errors?.join('; ')||'No usable publisher feed';
  else if (v.robots?.allowed===false) reason='Publisher robots policy excludes collection';
  else if (v.duplicateOf) reason=`Alias of ${v.duplicateOf}`;
  else if (/stayingahead\.ai|youtube\.com/i.test(source.url)) reason='Creator digest excluded from Dhivi';
  let alias;
  if (!reason) {
    for (const url of [source.url,v.finalUrl].filter(Boolean)) if(seen.has(key(url))) alias=seen.get(key(url));
    if(v.contentFingerprint && fingerprints.has(v.contentFingerprint)) alias=fingerprints.get(v.contentFingerprint);
    if(alias) reason=`Duplicate feed of ${alias}`;
  }
  if (!reason) {
    const record=metadata(source);
    active.push(record);
    for(const url of [source.url,v.finalUrl].filter(Boolean)) seen.set(key(url),record.id);
    if(v.contentFingerprint) fingerprints.set(v.contentFingerprint,record.id);
  }
  audit.push({id:source.id,name:source.name,url:source.url,publisher:source.publisher,discoveryUrl:source.discoveryUrl,auditFile:source.auditFile,active:!reason,...(reason?{reason}:{}),validation:v});
}
if(new Set(active.map(source=>source.id)).size!==active.length) throw new Error('Duplicate source identifiers');
const stats={
  screened:new Set(candidates.map(source=>key(source.url))).size,
  active:active.length,publishers:new Set(active.map(source=>source.publisher)).size,
  kinds:Object.fromEntries(['publisher','official','research'].map(kind=>[kind,active.filter(source=>source.kind===kind).length])),
  verifiedAt:candidates.map(source=>source.validation?.checkedAt).filter(Boolean).sort().at(-1),
  fingerprint:createHash('sha256').update(JSON.stringify(active)).digest('hex').slice(0,16),
};
const outputs=new Map([
  ['netlify/functions/lib/source-registry.mjs',`// Generated by npm run sources:build from HTTP/XML-screened publisher feeds.\nexport const SOURCE_CATALOG_STATS = ${JSON.stringify(stats,null,2)};\nexport const SOURCE_REGISTRY = ${JSON.stringify(active,null,2)};\n`],
  ['public/source-audit.json',JSON.stringify({stats,sources:audit},null,2)+'\n'],
  ['docs/source-audit.md',`# Dhivi source audit\n\n${stats.screened} distinct endpoints screened; **${stats.active} active feeds across ${stats.publishers} publisher groups**. Checked ${stats.verifiedAt}. Counts distinguish feeds from publishers. Multiple sections from one publisher are grouped when balancing the live feed.\n\nOnly HTTP/XML-validated, nonduplicate publisher feeds enter the registry. Failed, blocked, robots-excluded and alias endpoints remain in the JSON audit. Mixed feeds require AI relevance filtering. Journal issue feeds without a reliable original publication date are excluded. Current news must still have its own publisher publication date within the past 24 hours; a working feed may contain no qualifying stories today.\n\nReproduce with the catalog scripts, then **npm run sources:build**. The full evidence is in [the JSON audit](../public/source-audit.json) and the source-candidate files under data/.\n\n| Source | Publisher | Type | Feed |\n|---|---|---|---|\n${active.map(source=>`| ${source.name.replaceAll('|','/')} | ${source.publisher.replaceAll('|','/')} | ${source.contentType||source.kind} | [RSS/Atom](${source.url}) |`).join('\n')}\n`],
]);
let mismatches=0;
for(const [path,content] of outputs) {
  const destination=new URL(path,root);
  if(process.argv.includes('--check')) {
    const existing=await fs.readFile(destination,'utf8').catch(()=>null);
    if(existing!==content){console.error(`Registry output needs rebuilding: ${path}`);mismatches++;}
  } else {
    await fs.mkdir(new URL('./',destination),{recursive:true});
    await fs.writeFile(destination,content);
  }
}
console.log(JSON.stringify(stats));
if(mismatches) process.exitCode=1;
